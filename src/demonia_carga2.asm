arranca_trozo2:		; Direccion de ejecucion que pide la entrada 2 de la tabla de 0x8180
	ld hl,00000h		;c050   ; HL = 0, para poner a cero dos variables de sistema de un golpe
	ld (0f3eah),hl		;c053   ; BAKCLR y BDRCLR: fondo y borde negros
	ld (0f3dbh),hl		;c056   ; CLIKSW = 0 (sin clic de tecla) y CSRY = 0
	ld a,0f2h		;c059   ; RG1SAV: el valor que el VDP tendra en su registro 1
	ld (0f3e0h),a		;c05b   ; 0xF2 = pantalla encendida, interrupcion activa y sprites de 16x16
	call 00072h		;c05e   ; BIOS INIGRP - Switches to SCREEN 2 (high resolution screen with 256*192 pixels) | SCREEN 2, ya con ese registro 1
	call sube_patrones_y_colores		;c061   ; Sube patrones y colores
	call sube_nombres		;c064   ; Y los nombres
	call 000c0h		;c067   ; BIOS BEEP - Generates beep | Dos pitidos: este trozo esta
	call 000c0h		;c06a   ; BIOS BEEP - Generates beep
	ret			;c06d   ; Vuelve al cargador

