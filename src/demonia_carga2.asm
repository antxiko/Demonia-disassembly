sube_patrones_y_colores:		; Los 2048 de patrones a los tres tercios, y luego los 2048 de color
	ld hl,0b000h		;c000   ; Origen: la tabla de patrones
	ld de,00000h		;c003   ; Destino: primer tercio de la tabla de patrones de la VRAM
	ld bc,00800h		;c006   ; 2048 bytes, un tercio
	push hl			;c009
	push bc			;c00a
	call 0005ch		;c00b   ; BIOS LDIRVM - Block transfers to VRAM from memory
	pop bc			;c00e
	pop hl			;c00f
	ld de,00800h		;c010   ; Segundo tercio, con el MISMO origen
	push hl			;c013
	push bc			;c014
	call 0005ch		;c015   ; BIOS LDIRVM - Block transfers to VRAM from memory
	pop bc			;c018
	pop hl			;c019
	ld de,01000h		;c01a   ; Tercer tercio, igual
	call 0005ch		;c01d   ; BIOS LDIRVM - Block transfers to VRAM from memory
	ld hl,0b800h		;c020   ; Origen: la tabla de colores
	ld de,02000h		;c023   ; Primer tercio de la tabla de color de la VRAM
	ld bc,00800h		;c026
	push hl			;c029
	push bc			;c02a
	call 0005ch		;c02b   ; BIOS LDIRVM - Block transfers to VRAM from memory
	pop bc			;c02e
	pop hl			;c02f
	ld de,02800h		;c030   ; Segundo tercio de color
	push hl			;c033
	push bc			;c034
	call 0005ch		;c035   ; BIOS LDIRVM - Block transfers to VRAM from memory
	pop bc			;c038
	pop hl			;c039
	ld de,03000h		;c03a   ; Tercer tercio de color; sale por aqui, con un jp en lugar de call y ret
	jp 0005ch		;c03d   ; BIOS LDIRVM - Block transfers to VRAM from memory
sube_nombres:		; Vuelca las 24x32 casillas
	ld hl,0ad00h		;c040   ; Origen: la tabla de nombres del propio bloque
	ld de,01800h		;c043   ; Destino: la tabla de nombres de la VRAM
	ld bc,00300h		;c046   ; 768 bytes, la pantalla entera
	jp 0005ch		;c049   ; BIOS LDIRVM - Block transfers to VRAM from memory

